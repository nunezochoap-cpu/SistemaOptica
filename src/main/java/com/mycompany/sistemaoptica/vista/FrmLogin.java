    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
        // TODO add your handling code here:
    String correo = txtCorreo.getText().trim();
    String contraseña = new String(txtContraseña.getPassword());

    if (correo.isEmpty() || contraseña.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Ingrese el correo y la contraseña.");
        return;
    }

    com.mycompany.sistemaoptica.dao.impl.UsuarioDAOImpl dao =
            new com.mycompany.sistemaoptica.dao.impl.UsuarioDAOImpl();

    com.mycompany.sistemaoptica.model.Usuario usuario =
            dao.buscarPorCorreo(correo);

    if (usuario == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Correo no registrado o usuario inactivo.");
        return;
    }

    boolean contraseñaCorrecta =
            com.mycompany.sistemaoptica.service.Seguridad
                    .verificarContraseña(
                            contraseña, usuario.getContraseña());

    if (!contraseñaCorrecta) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "La contraseña es incorrecta.");
        return;
    }

        if (usuario.getRol().equalsIgnoreCase("Vendedor")) {

                 FrmVendedor vendedor = new FrmVendedor();
                  vendedor.setLocationRelativeTo(null);
              vendedor.setVisible(true);
                this.dispose();

            } else if (usuario.getRol().equalsIgnoreCase("Cliente")) {

             ClienteDAOImpl clienteDAO = new ClienteDAOImpl();

              Cliente cliente = clienteDAO.buscarPorUsuarioID(usuario.getUsuarioID());

               if (cliente != null) {

                   FrmClientePrincipal principal = new FrmClientePrincipal(cliente.getClienteID());

                      principal.setLocationRelativeTo(null);
                       principal.setVisible(true);

                      this.dispose();

                } else {
                   JOptionPane.showMessageDialog(this,
                  "No se encontró el registro del cliente.");
                }
            }

          
        
    
    }//GEN-LAST:event_btnIniciarSesionActionPerformed

