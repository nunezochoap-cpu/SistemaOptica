    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
       
    String nombre = txtCliente.getText().trim();
    String desde = txtDesde.getText().trim();
    String hasta = txtHasta.getText().trim();

    try {

        if (!desde.isEmpty() && !desde.matches("\\d{4}-\\d{2}-\\d{2}")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La fecha Desde debe tener formato yyyy-MM-dd");
            return;
        }

        if (!hasta.isEmpty() && !hasta.matches("\\d{4}-\\d{2}-\\d{2}")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La fecha Hasta debe tener formato yyyy-MM-dd");
            return;
        }

        if (!desde.isEmpty() && !hasta.isEmpty()
                && desde.compareTo(hasta) > 0) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "La fecha Desde no puede ser mayor que Hasta");
            return;
        }

        tblHistorialVentas.setModel(
                dao.buscarPorFiltros(nombre, desde, hasta)
        );

        int cantidad = tblHistorialVentas.getRowCount();
        double total = 0;

        for (int i = 0; i < cantidad; i++) {

            total += Double.parseDouble(
                    tblHistorialVentas.getValueAt(i, 5).toString()
            );
        }

        txtTotalVentas.setText(String.valueOf(cantidad));
        txtMontoTotal.setText(String.format("%.2f", total));

        if (cantidad == 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se encontraron ventas.");
        }

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Error al buscar: " + e.getMessage());
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

