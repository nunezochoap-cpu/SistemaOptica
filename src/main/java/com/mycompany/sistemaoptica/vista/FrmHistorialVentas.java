    private void BtnExportatExcelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnExportatExcelActionPerformed
        // TODO add your handling code here:
            javax.swing.JFileChooser guardar = new javax.swing.JFileChooser();

          guardar.setSelectedFile(
            new java.io.File("HistorialVentas.xlsx")
        );

         int opcion = guardar.showSaveDialog(this);

         if (opcion == javax.swing.JFileChooser.APPROVE_OPTION) {

           java.io.File archivo = guardar.getSelectedFile();

            if (!archivo.getName().toLowerCase().endsWith(".xlsx")) {
            archivo = new java.io.File(archivo.getAbsolutePath() + ".xlsx");
        }

        try {

            org.apache.poi.xssf.usermodel.XSSFWorkbook libro =
                    new org.apache.poi.xssf.usermodel.XSSFWorkbook();

            org.apache.poi.ss.usermodel.Sheet hoja =
                    libro.createSheet("Historial de Ventas");

            javax.swing.table.TableModel modelo =
                    tblHistorialVentas.getModel();

            // Encabezados
            org.apache.poi.ss.usermodel.Row encabezado =
                    hoja.createRow(0);

            for (int i = 0; i < modelo.getColumnCount(); i++) {
                encabezado.createCell(i).setCellValue(
                        modelo.getColumnName(i)
                );
            }

            // Datos de la tabla
            for (int i = 0; i < modelo.getRowCount(); i++) {

                org.apache.poi.ss.usermodel.Row fila =
                        hoja.createRow(i + 1);

                for (int j = 0; j < modelo.getColumnCount(); j++) {

                    Object valor = modelo.getValueAt(i, j);

                    fila.createCell(j).setCellValue(
                            valor == null ? "" : valor.toString()
                    );
                }
            }

            // Ajustar columnas
            for (int i = 0; i < modelo.getColumnCount(); i++) {
                hoja.autoSizeColumn(i);
            }

            try (java.io.FileOutputStream salida =
                    new java.io.FileOutputStream(archivo)) {

                libro.write(salida);
            }

            libro.close();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Historial exportado correctamente a Excel."
            );

        } catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Error al exportar: " + e.getMessage()
            );
        }
    }

    }//GEN-LAST:event_BtnExportatExcelActionPerformed

