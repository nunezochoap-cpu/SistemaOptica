    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
        // TODO add your handling code here:
        
        int fila = tblProductos.getSelectedRow();
        
        if(fila >= 0){
            txtNombre.setText(modelo.getValueAt(fila, 1).toString());
            cbmTipo.setSelectedItem(modelo.getValueAt(fila, 2).toString());
            txtMarca.setText(modelo.getValueAt(fila, 3).toString());
            
            txtMaterial.setText(
                    modelo.getValueAt(fila, 4) == null ?"":
                            modelo.getValueAt(fila, 4).toString()
            );
            
            txtForma.setText(
            modelo.getValueAt(fila, 5) == null ? "" :
                    modelo.getValueAt(fila, 5).toString()
            );
            
            txtPrecio.setText(modelo.getValueAt(fila, 6).toString());
            txtStock.setText(modelo.getValueAt(fila, 7).toString());
            
            
        }
    }//GEN-LAST:event_tblProductosMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:  
        int fila = tblProductos.getSelectedRow();
        
        if (fila <0) {
            JOptionPane.showMessageDialog(this,"Seleccione un producto de la tabla.");
            return;
        }
        
        try{
            Producto p = new Producto();
            
            p.setProductoID(
            Integer.parseInt(modelo.getValueAt(fila, 0).toString()));
            p.setNombre(txtNombre.getText().trim());
            p.setTipo(cbmTipo.getSelectedItem().toString());
            p.setMarca(txtMarca.getText().trim());
            p.setMaterial(txtForma.getText().trim());
            p.setForma(txtForma.getText().trim());
            p.setPrecio(Double.parseDouble(txtPrecio.getText().trim()));
            p.setStock(Integer.parseInt(txtStock.getText().trim()));
            
            if(servicio.actualizar(p)){
                JOptionPane.showMessageDialog(this,"Producto actualizado correctamente.");
                cargarProductos();
                limpiarCampos();
            }else{
                JOptionPane.showMessageDialog(this,"No se pudo actualizar el Producto.");
            }
            
        }catch(NumberFormatException e ){
            JOptionPane.showMessageDialog(this,
                    "El precio y el stock deben ser numeros Validos.");
        }catch (IllegalArgumentException e ){
            JOptionPane.showMessageDialog(this,e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tblProductos.getSelectedRow();
        
        if(fila < 0 ){
            JOptionPane.showMessageDialog(this,"Seleccione un prodcuto de la tabla.");
            return;
        }
        
        int respuesta = JOptionPane.showConfirmDialog(
        this,"¿Está seguro de eliminar este producto?","confirmar eliminacion",JOptionPane.YES_NO_OPTION);
        
         if (respuesta == JOptionPane.YES_OPTION) {
        try {
            int id = Integer.parseInt(
                    modelo.getValueAt(fila, 0).toString());

            if (servicio.eliminar(id)) {
                JOptionPane.showMessageDialog(this,
                        "Producto eliminado correctamente.");
                cargarProductos();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this,
                        "No se pudo eliminar el producto.");
            }

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
         }
       }
    }//GEN-LAST:event_btnEliminarActionPerformed

