    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        try{
            Producto p = new Producto();
            
            p.setNombre(txtNombre.getText().trim());
            p.setTipo(cbmTipo.getSelectedItem().toString());
            p.setMarca(txtMarca.getText().trim());
            p.setMaterial(txtMaterial.getText().trim());
            p.setForma(txtForma.getText().trim());
            p.setPrecio(Double.parseDouble(txtPrecio.getText()));
            p.setStock(Integer.parseInt(txtStock.getText()));
            
            if(servicio.registrar(p)){
                
                JOptionPane.showMessageDialog(this,
                        "Producto registrado Correctamente.");
                
                cargarProductos();
                limpiarCampos();
                
            }else{ JOptionPane.showMessageDialog(this,
                    "No se pudo registrar el Producto.");
                
            }
            
        }catch (NumberFormatException e ){
            JOptionPane.showMessageDialog(this,
                    "Ingrese un precio y un Stock Validos.");
        }catch (IllegalArgumentException e ){
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
        
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

