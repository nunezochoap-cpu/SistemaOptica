    private void cargarProductos(){
        
        ProductoDAOImpl dao  = new ProductoDAOImpl();
        
        cbmProducto.removeAllItems();
        listaProductos.clear();
        
        for(Producto p : dao.listar()){
            
            if (p.getStock() > 0) {
                
                
                cbmProducto.addItem(p.getNombre());
                
                listaProductos.add(p);
            }
        }
        
    }

