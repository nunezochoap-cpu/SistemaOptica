    private void btnRegistrarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVentaActionPerformed
        // TODO add your handling code here:
        
         int clienteID;

    try {
        clienteID = Integer.parseInt(txtClienteID.getText().trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Primero debe buscar un cliente válido.");
        return;
    }

    if (txtNombreCliente.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Debe buscar y seleccionar un cliente.");
        return;
    }

  
    DefaultTableModel modelo =
            (DefaultTableModel) tblDetalleVenta.getModel();

    if (modelo.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this,
                "Agregue al menos un producto a la venta.");
        return;
    }

   
    List<DetalleVenta> detalles = new ArrayList<>();

    try {
        for (int i = 0; i < modelo.getRowCount(); i++) {

            DetalleVenta d = new DetalleVenta();

            int productoID = Integer.parseInt(
                    modelo.getValueAt(i, 0).toString());

            int cantidad = Integer.parseInt(
                    modelo.getValueAt(i, 3).toString());

            d.setProductoID(productoID);
            d.setCantidad(cantidad);

            detalles.add(d);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Hay datos incorrectos en el detalle de venta.");
        return;
    }

    // Registrar venta en SQL Server
    VentaDAOImpl dao = new VentaDAOImpl();

    int ventaID = dao.registrarVenta(clienteID, detalles);

    if (ventaID > 0) {

        JOptionPane.showMessageDialog(this,
                "Venta registrada correctamente.\n"
                + "Número de venta: " + ventaID
                + "\nISV aplicado: 15%");

        // Limpiar detalle
        modelo.setRowCount(0);

        // Reiniciar total
        txtTotal.setText("0.00");

        // Actualizar productos y existencias
        cargarProductos();

        spCantidad.setValue(0);

    } else {
        JOptionPane.showMessageDialog(this,
                "No se pudo registrar la venta.\n"
                + "Verifique que el cliente tenga una medición "
                + "y que los productos tengan existencias.",
                "Error al registrar",
                JOptionPane.ERROR_MESSAGE);
    }

        
    }//GEN-LAST:event_btnRegistrarVentaActionPerformed

