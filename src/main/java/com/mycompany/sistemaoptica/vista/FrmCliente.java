    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        
        try {
            Cliente c = new Cliente();
            
            c.setUsuarioID(Integer.parseInt(txtUsuarioID.getText().trim())
            );
            
            c.setDni(txtDNI.getText().trim());
            c.setTelefono(txtTelefono.getText().trim());
            
            if (servicio.registrar(c)){
                JOptionPane.showMessageDialog(this, "Cliente registrado Correctamente.");
                
                
                cargarClientes();
                
                txtUsuarioID.setText("");
                txtDNI.setText("");
                txtTelefono.setText("");
    
            }else{
                JOptionPane.showMessageDialog(this,
                        "No se pudo registrar el cliente"
                +"Verifique que el UsuarioID exista"
                + "y que el DNI no este repetido.");
            }
            
        }catch (NumberFormatException e ){
            JOptionPane.showMessageDialog(this,"El ID del usurio debe ser un numero Valido.");
        }catch (IllegalArgumentException e ){
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
          try {
        if (txtClienteID.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el ID del cliente que desea buscar.");
            return;
        }

        int id = Integer.parseInt(txtClienteID.getText().trim());

        Cliente c = clienteDAO.buscarPorID(id);

        if (c != null) {

            txtUsuarioID.setText(String.valueOf(c.getUsuarioID()));
            txtDNI.setText(c.getDni());
            txtTelefono.setText(c.getTelefono());

            JOptionPane.showMessageDialog(this,
                    "Cliente encontrado correctamente.");

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se encontró el cliente.");

        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "El ID del cliente debe ser un número válido.");
    }

    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
         try {
        if (txtClienteID.getText().trim().isEmpty()
                || txtDNI.getText().trim().isEmpty()
                || txtTelefono.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Complete todos los campos.");
            return;
        }

        Cliente c = new Cliente();

        c.setClienteID(Integer.parseInt(txtClienteID.getText().trim()));
        c.setDni(txtDNI.getText().trim());
        c.setTelefono(txtTelefono.getText().trim());

        if (clienteDAO.actualizar(c)) {

            JOptionPane.showMessageDialog(this,
                    "Cliente actualizado correctamente.");

            cargarClientes();

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se pudo actualizar el cliente.");

        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "El ID del cliente debe ser un número válido.");
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        try {
        if (txtClienteID.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el ID del cliente que desea eliminar.");
            return;
        }

        int id = Integer.parseInt(txtClienteID.getText().trim());

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar este cliente?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmar == JOptionPane.YES_OPTION) {

            if (clienteDAO.eliminar(id)) {

                JOptionPane.showMessageDialog(this,
                        "Cliente eliminado correctamente.");

                cargarClientes();

                txtClienteID.setText("");
                txtUsuarioID.setText("");
                txtDNI.setText("");
                txtTelefono.setText("");

            } else {

                JOptionPane.showMessageDialog(this,
                        "No se pudo eliminar el cliente.");

            }
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "El ID debe ser un número válido.");
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

