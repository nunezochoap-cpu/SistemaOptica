    private void cargarClientes(){
        modelo.setRowCount(0);
        
        List<Cliente>lista = clienteDAO.listar();
        
        for (Cliente c : lista){
            modelo.addRow(new Object[]{
                c.getClienteID(),
                c.getUsuarioID(),
                c.getDni(),
                c.getTelefono()
            });
        }
    }
    

